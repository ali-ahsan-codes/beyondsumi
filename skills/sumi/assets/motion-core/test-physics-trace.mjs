import assert from 'node:assert/strict';
import {createPhysicsTrace} from './physics-trace.mjs';
const trace = createPhysicsTrace({fps:24,planSha256:'a'.repeat(64)});
const p = {sole:[1,2]};
trace.record({action:'walk',character:'hero',frame:1,points:p});
p.sole[0] = 100;
trace.record({action:'walk',character:'hero',frame:0,points:{sole:[1,2]}});
assert.deepEqual(trace.toJSON().actions.walk.map(x=>x.frame),[0,1]);
assert.equal(trace.toJSON().actions.walk[1].points.sole[0],1);
const result=trace.toJSON();result.actions.walk[0].points.sole[0]=99;
assert.equal(trace.toJSON().actions.walk[0].points.sole[0],1);
assert.throws(()=>trace.record({action:'walk',character:'hero',frame:1,points:p}),/Duplicate/);
assert.throws(()=>trace.record({action:'walk',character:'hero',frame:2,points:{sole:[NaN,0]}}),/Finite/);
assert.throws(()=>trace.record({action:'walk',character:'hero',frame:.5,points:p}),/Invalid/);
assert.throws(()=>createPhysicsTrace({fps:0,planSha256:'bad'}));
console.log('Physics trace: sorted frames, immutable snapshots, duplicate/invalid input rejection passed');
